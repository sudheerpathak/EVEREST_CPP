#include <iostream>
using namespace std;

int main()
{
int a;
cout<<"Today's task is to show all assignment operator";
cin>>a;

a+=a;
cout<<"The sum of = "<<a<<endl;

a-=10;
cout<<"The difference is ="<<a<<endl;

a*4;
cout<<"The product is = "<<a<<endl;

a/=4;
cout<<"The division is ="<<a<<endl;

a%=3;
cout<<"The reminder is ="<<a<<endl;

return 0;

}